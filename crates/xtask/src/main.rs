fn install(args: &[String]) -> Result<()> {
    let mut source: Option<PathBuf> = None;
    let mut force = false;
    for arg in args {
        match arg.as_str() {
            "--force" => force = true,
            other if other.starts_with("--") => bail!("unknown flag `{other}`"),
            other => source = Some(PathBuf::from(other)),
        }
    }
    let Some(source) = source else {
        bail!("usage: cargo xtask plugins install <path> [--force]");
    };
    let source = source
        .canonicalize()
        .with_context(|| format!("cannot open {}", source.display()))?;

    let manifest_path = source.join("Cargo.toml");
    let manifest = fs::read_to_string(&manifest_path)
        .with_context(|| format!("{} is not a crate (no Cargo.toml)", source.display()))?;
    let doc: DocumentMut = manifest.parse().context("parsing the plugin Cargo.toml")?;
    let package = doc
        .get("package")
        .and_then(Item::as_table_like)
        .and_then(|table| table.get("name"))
        .and_then(Item::as_str)
        .ok_or_else(|| anyhow!("the plugin Cargo.toml has no package.name"))?;
    let id = package
        .strip_prefix("plugin-")
        .ok_or_else(|| anyhow!("package name `{package}` must start with `plugin-`"))?;
    validate_id(id)?;

    let lib_path = source.join("src/lib.rs");
    let lib = fs::read_to_string(&lib_path)
        .with_context(|| format!("{} has no src/lib.rs", source.display()))?;
    if !lib.contains("pub fn plugin(") {
        bail!(
            "plugins/<id>/src/lib.rs must expose `pub fn plugin() -> Arc<dyn Plugin>` so the \
             composition root can mount it"
        );
    }

    let destination = root().join("crates/plugins").join(id);
    if destination.exists() {
        if !force {
            bail!("crates/plugins/{id} already exists; pass --force to replace it");
        }
    }
    let ui_source = source.join("ui");
    let ui_destination = root().join("src/plugins").join(id);
    if ui_source.is_dir() && ui_destination.exists() && !force {
        bail!("src/plugins/{id} already exists; pass --force to replace it");
    }
    with_workspace_transaction(
        vec![
            destination.clone(),
            ui_destination.clone(),
            shop_api_manifest(),
            compose_path(),
            root().join("Cargo.lock"),
            root().join("dist"),
        ],
        || {
            if destination.exists() {
                fs::remove_dir_all(&destination)?;
            }
            copy_dir(&source, &destination)?;
            if ui_source.is_dir() {
                if ui_destination.exists() {
                    fs::remove_dir_all(&ui_destination)?;
                }
                copy_dir(&ui_source, &ui_destination)?;
            }
            add_dependency(id)?;
            sync()?;
            maybe_fault("after-sync")?;
            // Validate composition (and regenerate UI manifests) before rebuilding the SPA.
            maybe_fault("before-check")?;
            check()?;
            if ui_destination.is_dir() {
                run(npm(), &["run", "build"], &root())?;
            }
            Ok(())
        },
    )?;

    println!();
    println!("Plugin `{id}` is wired into the till.");
    println!("Next: `npm run app`, then turn it on in Settings → Plugins.");
    Ok(())
}

fn remove(args: &[String]) -> Result<()> {
    let mut id: Option<String> = None;
    let mut purge = false;
    let mut keep_source = false;
    let mut embedded = false;
    for arg in args {
        match arg.as_str() {
            "--purge" => purge = true,
            "--keep-source" => keep_source = true,
            "--embedded" => embedded = true,
            other if other.starts_with("--") => bail!("unknown flag `{other}`"),
            other => id = Some(other.to_string()),
        }
    }
    let Some(id) = id else {
        bail!("usage: cargo xtask plugins remove <id> [--purge] [--keep-source] [--embedded]");
    };
    validate_id(&id)?;

    let crate_dir = root().join("crates/plugins").join(&id);
    let disabled_dir = root().join("crates/plugins-disabled").join(&id);
    if !crate_dir.is_dir() && !disabled_dir.is_dir() {
        bail!("plugin `{id}` is not in crates/plugins or crates/plugins-disabled");
    }

    let ui = root().join("src/plugins").join(&id);
    let ui_existed = ui.exists();
    with_workspace_transaction(
        vec![
            crate_dir.clone(),
            disabled_dir.clone(),
            ui.clone(),
            shop_api_manifest(),
            compose_path(),
            root().join("Cargo.lock"),
            root().join("dist"),
            root().join("crates/plugins-disabled"),
        ],
        || {
            remove_dependency(&id)?;
            sync()?;
            maybe_fault("remove-after-sync")?;
            fs::create_dir_all(root().join("crates/plugins-disabled"))?;
            if crate_dir.is_dir() {
                if disabled_dir.exists() {
                    bail!("crates/plugins-disabled/{id} already exists; refusing to replace it");
                }
                fs::rename(&crate_dir, &disabled_dir)
                    .with_context(|| format!("moving crates/plugins/{id} out of the workspace"))?;
            }
            if !keep_source && ui.exists() {
                fs::remove_dir_all(&ui)?;
            }
            maybe_fault("remove-before-check")?;
            check()?;
            // Rebuild even when the UI directory was removed, otherwise the
            // bundled production frontend keeps the deleted plugin's chunks.
            if ui_existed {
                run(npm(), &["run", "build"], &root())?;
            }
            if purge {
                let sql = disabled_dir.join("uninstall.sql");
                let sql = if sql.is_file() {
                    Some(sql)
                } else {
                    crate_dir
                        .join("uninstall.sql")
                        .is_file()
                        .then(|| crate_dir.join("uninstall.sql"))
                };
                purge_plugin(&id, embedded, sql.as_deref())?;
            }
            Ok(())
        },
    )?;

    if purge {
        println!("Purged `{id}`: tables dropped by uninstall.sql, bookkeeping rows deleted.");
    } else {
        println!("Removed `{id}`. Its tables and settings are untouched.");
    }
    Ok(())
}

fn purge_plugin(id: &str, embedded: bool, sql: Option<&Path>) -> Result<()> {
    let mut command: Vec<String> = vec![
        "run".into(),
        "-q".into(),
        "-p".into(),
        "shop-api".into(),
        "--".into(),
        "--purge-plugin".into(),
        id.into(),
    ];
    if embedded {
        command.push("--embedded".into());
    }
    if let Some(sql) = sql {
        command.push("--sql".into());
        command.push(sql.to_string_lossy().into_owned());
    }
    let borrowed: Vec<&str> = command.iter().map(String::as_str).collect();
    run("cargo", &borrowed, &root())
}

fn list() -> Result<()> {
    run(
        "cargo",
        &["run", "-q", "-p", "shop-api", "--", "--list-plugins"],
        &root(),
    )
}

fn scaffold(args: &[String]) -> Result<()> {
    let mut id: Option<String> = None;
    let mut with_ui = false;
    for arg in args {
        match arg.as_str() {
            "--ui" => with_ui = true,
            other if other.starts_with("--") => bail!("unknown flag `{other}`"),
            other => id = Some(other.to_string()),
        }
    }
    let Some(id) = id else {
        bail!("usage: cargo xtask plugins new <id> [--ui]");
    };
    validate_id(&id)?;

    let crate_dir = root().join("crates/plugins").join(&id);
    if crate_dir.exists() {
        bail!("crates/plugins/{id} already exists");
    }
    fs::create_dir_all(crate_dir.join("src"))?;
    fs::create_dir_all(crate_dir.join("migrations"))?;

    let struct_name = format!("{}Plugin", pascal_case(&id));
    let title = title_case(&id);

    fs::write(
        crate_dir.join("Cargo.toml"),
        format!(
            "[package]\nname = \"plugin-{id}\"\nversion = \"0.1.0\"\nedition = \"2021\"\nlicense = \"MIT\"\n\n\
             [dependencies]\nasync-trait = \"0.1\"\naxum = {{ version = \"0.8\", features = [\"json\"] }}\n\
             platform-kernel = {{ path = \"../../platform-kernel\" }}\nserde = {{ version = \"1\", features = [\"derive\"] }}\n\
             serde_json = \"1\"\nsqlx = {{ version = \"0.8\", default-features = false, features = [\"runtime-tokio\", \"tls-rustls\", \"postgres\", \"uuid\"] }}\n"
        ),
    )?;
    fs::write(
        crate_dir.join("src/lib.rs"),
        format!(
            "use std::sync::Arc;\n\n\
             use platform_kernel::contract::Registrar;\n\
             use platform_kernel::manifest::PluginManifest;\n\
             use platform_kernel::migrate::Migration;\n\
             use platform_kernel::permission::Permission;\n\
             use platform_kernel::plugin::Plugin;\n\
             use platform_kernel::routes::{{PluginRoutes, RegistrationError}};\n\n\
             pub struct {struct_name};\n\n\
             /// Composition handle consumed by the generated `shop-api` plugin list.\n\
             pub fn plugin() -> Arc<dyn Plugin> {{\n    Arc::new({struct_name})\n}}\n\n\
             impl Plugin for {struct_name} {{\n    \
             fn manifest(&self) -> PluginManifest {{\n        \
             let mut manifest = PluginManifest::v1(\"{id}\", \"{title}\", \"0.1.0\");\n        \
             manifest.description = \"TODO: describe this plugin.\".into();\n        \
             manifest.permissions = vec![\n            \
             Permission::new(\"{id}.read\"),\n            \
             Permission::new(\"{id}.write\"),\n        ];\n        \
             manifest\n    }}\n\n    \
             fn migrations(&self) -> &'static [Migration] {{\n        &[]\n    }}\n\n    \
             fn register(&self, _registrar: &mut Registrar) {{}}\n\n    \
             fn routes(&self, _routes: &mut PluginRoutes) -> Result<(), RegistrationError> {{\n        Ok(())\n    }}\n}}\n"
        ),
    )?;
    fs::write(
        crate_dir.join("migrations/.gitkeep"),
        "Plugin SQL migrations live here. Migration::new(1, \"name\", include_str!(\"../migrations/001_x.sql\")).\n",
    )?;

    if with_ui {
        let ui_dir = root().join("src/plugins").join(&id);
        fs::create_dir_all(ui_dir.join("screens"))?;
        fs::write(
            ui_dir.join("index.ts"),
            format!(
                "import {{ defineUiPlugin }} from '../../platform/registry'\n\
                 import {{ metadata }} from './manifest.generated'\n\n\
                 export const {id}Plugin = defineUiPlugin({{\n  ...metadata,\n  \
                 pages: [\n    \
                 {{ path: '/{id}', title: '{title}', permission: '{id}.read', load: () => import('./screens/HomePage.svelte') }},\n  \
                 ],\n}})\n"
            ),
        )?;
        fs::write(
            ui_dir.join("manifest.generated.ts"),
            format!(
                "/* Placeholder until `cargo xtask plugins check` regenerates from Rust. */\n\
                 import type {{ UiPlugin }} from '../../platform/registry'\n\n\
                 export const metadata = {{\n  id: '{id}',\n  requiresBackend: true as const,\n  \
                 permissions: ['{id}.read', '{id}.write'] as string[],\n  \
                 nav: [{{ id: '{id}', label: '{title}', href: '/{id}', permission: '{id}.read', order: 60 }}] as UiPlugin['nav'],\n  \
                 settingsPages: [] as UiPlugin['settingsPages'],\n  \
                 reportPages: [] as UiPlugin['reportPages'],\n  \
                 slotsProvided: [] as string[],\n  \
                 contributions: [] as Array<{{ id: string; slot: string; order: number }}>,\n}}\n"
            ),
        )?;
        fs::write(
            ui_dir.join("screens/HomePage.svelte"),
            format!("<main class=\"stage\">\n  <h1>{title}</h1>\n  <p>Replace this screen with the plugin's content.</p>\n</main>\n"),
        )?;
    }

    add_dependency(&id)?;
    sync()?;
    run("cargo", &["check", "-p", "shop-api"], &root())?;
    if with_ui {
        run(npm(), &["run", "build"], &root())?;
    }

    println!();
    println!("Created plugin `{id}`. Run `npm run app`, then enable it in Settings → Plugins.");
    Ok(())
}

