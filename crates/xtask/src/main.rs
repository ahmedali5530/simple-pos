fn add_dependency(id: &str) -> Result<()> {
    let path = shop_api_manifest();
    let text = fs::read_to_string(&path)?;
    let mut doc: DocumentMut = text.parse()?;
    let key = format!("plugin-{id}");
    let present = doc
        .get("dependencies")
        .and_then(Item::as_table_like)
        .map(|table| table.contains_key(&key))
        .unwrap_or(false);
    if present {
        return Ok(());
    }
    let mut inline = toml_edit::InlineTable::new();
    inline.insert("path", Value::from(format!("../plugins/{id}")));
    if let Some(table) = doc
        .get_mut("dependencies")
        .and_then(Item::as_table_like_mut)
    {
        table.insert(&key, Item::Value(Value::InlineTable(inline)));
    } else {
        bail!("crates/shop-api/Cargo.toml has no [dependencies] table");
    }
    fs::write(&path, doc.to_string())?;
    println!("Added {key} to crates/shop-api/Cargo.toml");
    Ok(())
}

fn remove_dependency(id: &str) -> Result<()> {
    let path = shop_api_manifest();
    let text = fs::read_to_string(&path)?;
    let mut doc: DocumentMut = text.parse()?;
    let key = format!("plugin-{id}");
    let removed = doc
        .get_mut("dependencies")
        .and_then(Item::as_table_like_mut)
        .and_then(|table| table.remove(&key))
        .is_some();
    if removed {
        fs::write(&path, doc.to_string())?;
        println!("Removed {key} from crates/shop-api/Cargo.toml");
    }
    Ok(())
}

fn validate_id(id: &str) -> Result<()> {
    let ok = (2..=32).contains(&id.len())
        && id.starts_with(|c: char| c.is_ascii_lowercase())
        && id
            .chars()
            .all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_');
    if ok {
        Ok(())
    } else {
        bail!("`{id}` is not a valid plugin id (2–32 chars of [a-z0-9_], starting with a letter)")
    }
}

fn copy_dir(source: &Path, destination: &Path) -> Result<()> {
    fs::create_dir_all(destination)?;
    for entry in fs::read_dir(source)? {
        let entry = entry?;
        let name = entry.file_name();
        let name = name.to_string_lossy();
        if matches!(name.as_ref(), "target" | ".git" | "node_modules" | "ui") {
            continue;
        }
        let from = entry.path();
        let to = destination.join(name.as_ref());
        if entry.file_type()?.is_dir() {
            copy_dir(&from, &to)?;
        } else {
            fs::copy(&from, &to).with_context(|| format!("copying {}", from.display()))?;
        }
    }
    Ok(())
}

fn run(program: &str, args: &[&str], cwd: &Path) -> Result<()> {
    println!("$ {program} {}", args.join(" "));
    let status = Command::new(program)
        .args(args)
        .current_dir(cwd)
        .status()
        .with_context(|| format!("could not start `{program}`"))?;
    if !status.success() {
        bail!("`{program} {}` failed ({status})", args.join(" "));
    }
    Ok(())
}

fn npm() -> &'static str {
    if cfg!(windows) {
        "npm.cmd"
    } else {
        "npm"
    }
}

fn pascal_case(id: &str) -> String {
    id.split('_')
        .filter(|part| !part.is_empty())
        .map(|part| {
            let mut chars = part.chars();
            match chars.next() {
                Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect()
}

fn title_case(id: &str) -> String {
    id.replace('_', " ")
        .split_whitespace()
        .map(|word| {
            let mut chars = word.chars();
            match chars.next() {
                Some(first) => first.to_ascii_uppercase().to_string() + chars.as_str(),
                None => String::new(),
            }
        })
        .collect::<Vec<_>>()
        .join(" ")
}
