//! Repository tasks. Run through the `xtask` alias: `cargo xtask plugins <command>`.
//!
//! The plugin commands keep static linking from leaking into the core: a plugin is a directory,
//! `install` wires it into the workspace and regenerates the composition root, and `remove`
//! unwires it without deleting the shop's data.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::{anyhow, bail, Context, Result};
use toml_edit::{DocumentMut, Item, Value};

fn main() {
    if let Err(error) = cli() {
        eprintln!("error: {error:#}");
        std::process::exit(1);
    }
}

fn cli() -> Result<()> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args.split_first() {
        Some((group, rest)) if group == "plugins" => plugins(rest),
        _ => {
            print_help();
            Ok(())
        }
    }
}

fn plugins(args: &[String]) -> Result<()> {
    let Some((command, rest)) = args.split_first() else {
        print_help();
        return Ok(());
    };
    match command.as_str() {
        "sync" => sync(),
        "check" => check(),
        "list" => list(),
        "install" => install(rest),
        "remove" => remove(rest),
        "new" => scaffold(rest),
        other => bail!("unknown command `plugins {other}`; run `cargo xtask` for help"),
    }
}

fn print_help() {
    println!(
        "\
Usage: cargo xtask plugins <command>

Commands:
  sync                 Regenerate crates/shop-api/src/compose.rs from shop-api dependencies
  check                Fail if compose.rs is out of date (CI)
  list                 Print the compiled plugins, in dependency order
  install <path>       Copy a plugin crate in, wire it up and rebuild
  remove <id>          Unwire a plugin; keeps its data unless --purge
  new <id>             Scaffold a new plugin crate (--ui also scaffolds the Svelte descriptor)

Flags:
  --force              Replace an existing plugin directory on install
  --keep-source        On remove, leave the crate on disk but stop composing it
  --purge              On remove, run uninstall.sql and delete bookkeeping rows
  --embedded           On purge, use the desktop till's bundled database
  --ui                 On new, add a UI descriptor and a placeholder screen"
    );
}

// ---------------------------------------------------------------------------------------------
// Paths
// ---------------------------------------------------------------------------------------------

fn root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .and_then(Path::parent)
        .expect("xtask lives in crates/xtask")
        .to_path_buf()
}

fn shop_api_manifest() -> PathBuf {
    root().join("crates/shop-api/Cargo.toml")
}

fn compose_path() -> PathBuf {
    root().join("crates/shop-api/src/compose.rs")
}

// ---------------------------------------------------------------------------------------------
// Composition root
// ---------------------------------------------------------------------------------------------

struct PluginCrate {
    id: String,
    ident: String,
    feature: String,
}

fn plugin_crates() -> Result<Vec<PluginCrate>> {
    let text = fs::read_to_string(shop_api_manifest()).context("reading shop-api/Cargo.toml")?;
    let doc: DocumentMut = text.parse().context("parsing shop-api/Cargo.toml")?;
    let mut plugins = Vec::new();
    if let Some(table) = doc.get("dependencies").and_then(Item::as_table_like) {
        for (name, _) in table.iter() {
            if let Some(id) = name.strip_prefix("plugin-") {
                plugins.push(PluginCrate {
                    id: id.to_string(),
                    ident: name.replace('-', "_"),
                    feature: name.to_string(),
                });
            }
        }
    }
    plugins.sort_by(|a, b| a.id.cmp(&b.id));
    Ok(plugins)
}

fn render(plugins: &[PluginCrate]) -> String {
    let mut out = String::new();
    out.push_str("// @generated by `cargo xtask plugins sync` — do not edit by hand.\n");
    out.push_str("// Source of truth: the `plugin-*` entries in crates/shop-api/Cargo.toml.\n\n");
    out.push_str("use std::sync::Arc;\n\n");
    out.push_str("use platform_kernel::plugin::Plugin;\n\n");
    out.push_str("pub fn plugins() -> Vec<Arc<dyn Plugin>> {\n    #[allow(unused_mut)]\n    let mut plugins: Vec<Arc<dyn Plugin>> = Vec::new();\n");
    for plugin in plugins {
        out.push_str(&format!(
            "    #[cfg(feature = \"{}\")]\n    plugins.push({}::plugin());\n",
            plugin.feature, plugin.ident
        ));
    }
    out.push_str("    plugins\n}\n\n");
    out.push_str(
        "#[cfg(test)]\nmod tests {\n    use super::*;\n\n    #[test]\n    \
         fn every_compiled_plugin_has_a_valid_manifest() {\n        \
         let catalog = platform_kernel::registry::PluginCatalog::build(plugins())\n            \
         .expect(\"compiled plugin set must form a valid catalog\");\n        \
         for manifest in catalog.manifests() {\n            \
         manifest.validate().expect(\"manifest validates\");\n        }\n    }\n}\n",
    );
    out
}

fn sync() -> Result<()> {
    let plugins = plugin_crates()?;
    let rendered = render(&plugins);
    let path = compose_path();
    if fs::read_to_string(&path).ok().as_deref() == Some(rendered.as_str()) {
        println!(
            "compose.rs is already up to date ({} plugins)",
            plugins.len()
        );
        return Ok(());
    }
    fs::write(&path, rendered).with_context(|| format!("writing {}", path.display()))?;
    println!("Wrote {} ({} plugins)", path.display(), plugins.len());
    Ok(())
}

/// Test hook: set `CHASKA_XTASK_FAIL_AT` to a stage name to abort install/remove mid-flight.
fn maybe_fault(stage: &str) -> Result<()> {
    if std::env::var("CHASKA_XTASK_FAIL_AT").ok().as_deref() == Some(stage) {
        bail!("injected failure at {stage}");
    }
    Ok(())
}

fn check() -> Result<()> {
    maybe_fault("check")?;
    let plugins = plugin_crates()?;
    let rendered = render(&plugins);
    let current = fs::read_to_string(compose_path()).unwrap_or_default();
    if current != rendered {
        bail!(
            "compose.rs is out of date; run `cargo xtask plugins sync`\n  \
             ({} plugin crates are wired into shop-api)",
            plugins.len()
        );
    }
    let manifests = compiled_manifests()?;
    for plugin in &plugins {
        let dir = root().join("crates/plugins").join(&plugin.id);
        let text = fs::read_to_string(dir.join("src/lib.rs"))
            .with_context(|| format!("wired plugin {} has no src/lib.rs", plugin.id))?;
        if !text.contains(&format!("PluginManifest::v1(\"{}\"", plugin.id)) {
            bail!(
                "plugin-{} Rust manifest id does not match its crate name",
                plugin.id
            );
        }
        validate_manifest_dependencies(plugin, &manifests)?;
    }
    for entry in fs::read_dir(root().join("crates/plugins"))? {
        let entry = entry?;
        if !entry.file_type()?.is_dir() {
            continue;
        }
        let id = entry.file_name().to_string_lossy().into_owned();
        if !plugins.iter().any(|plugin| plugin.id == id) {
            bail!("crates/plugins/{id} is neither wired nor explicitly disabled");
        }
    }
    let manifest_path = root().join("target/plugin-manifests.json");
    fs::create_dir_all(manifest_path.parent().expect("target directory"))?;
    fs::write(&manifest_path, serde_json::to_vec_pretty(&manifests)?)?;
    run(
        "node",
        &["scripts/codegen-plugin-ui.mjs"],
        &root(),
    )?;
    run(
        "node",
        &[
            "scripts/check-plugin-ui.mjs",
            manifest_path.to_str().expect("target path is UTF-8"),
        ],
        &root(),
    )?;
    println!("Composition is valid ({} plugins)", plugins.len());
    Ok(())
}

fn compiled_manifests() -> Result<Vec<serde_json::Value>> {
    let output = Command::new("cargo")
        .args(["run", "-q", "-p", "shop-api", "--", "--list-plugins-json"])
        .current_dir(root())
        .output()
        .context("reading compiled plugin manifests")?;
    if !output.status.success() {
        bail!("could not build the plugin catalog to validate dependencies");
    }
    Ok(serde_json::from_slice(&output.stdout)?)
}

fn validate_manifest_dependencies(
    plugin: &PluginCrate,
    manifests: &[serde_json::Value],
) -> Result<()> {
    let manifest = manifests
        .iter()
        .find(|manifest| manifest["id"] == plugin.id)
        .ok_or_else(|| {
            anyhow!(
                "plugin {} is missing from the compiled manifest catalog",
                plugin.id
            )
        })?;
    let mut declared = std::collections::BTreeSet::new();
    for field in ["requires", "optional"] {
        if let Some(dependencies) = manifest[field].as_array() {
            for dependency in dependencies {
                if let Some(id) = dependency["id"].as_str() {
                    declared.insert(id.to_string());
                }
            }
        }
    }
    let manifest_path = root()
        .join("crates/plugins")
        .join(&plugin.id)
        .join("Cargo.toml");
    let source: DocumentMut = fs::read_to_string(&manifest_path)?.parse()?;
    let mut cargo = std::collections::BTreeSet::new();
    if let Some(deps) = source.get("dependencies").and_then(Item::as_table_like) {
        for (name, _) in deps.iter() {
            if let Some(id) = name.strip_prefix("plugin-") {
                cargo.insert(id.to_string());
            }
        }
    }
    if let Some(missing) = cargo.difference(&declared).next() {
        bail!("plugin-{} directly depends on plugin-{missing} in Cargo.toml but does not declare it in requires or optional", plugin.id);
    }
    Ok(())
}

