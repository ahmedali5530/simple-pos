#!/usr/bin/env node
/**
 * Generate src/plugins/<id>/manifest.generated.ts from the compiled Rust plugin
 * catalog (target/plugin-manifests.json). Page loaders and slot components stay
 * hand-authored in index.ts.
 *
 * Usage:
 *   node scripts/codegen-plugin-ui.mjs              # write files
 *   node scripts/codegen-plugin-ui.mjs --check       # fail if out of date
 */
import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const checkOnly = process.argv.includes('--check')
const manifestPath = path.join(root, 'target/plugin-manifests.json')
if (!fs.existsSync(manifestPath)) {
  console.error('Missing target/plugin-manifests.json; run `cargo xtask plugins check` first.')
  process.exit(1)
}

const manifests = JSON.parse(fs.readFileSync(manifestPath, 'utf8'))
const uiRoot = path.join(root, 'src/plugins')
let wrote = 0
let stale = 0

function tsString(value) {
  return JSON.stringify(value ?? '')
}

function renderNav(items) {
  return `[${(items ?? [])
    .map((item) => {
      const children = item.children?.length ? `, children: ${renderNav(item.children)}` : ''
      const href = item.href ? `, href: ${tsString(item.href)}` : ''
      const permission = item.permission ? `, permission: ${tsString(item.permission)}` : ''
      return `{ id: ${tsString(item.id)}, label: ${tsString(item.label)}${href}${permission}, order: ${item.order ?? 0}${children} }`
    })
    .join(', ')}]`
}

function renderSettings(items) {
  return `[${(items ?? [])
    .map((item) => {
      const children = item.children?.length ? `, children: ${renderSettings(item.children)}` : ''
      const href = item.href ? `, href: ${tsString(item.href)}` : ''
      const permission = item.permission ? `, permission: ${tsString(item.permission)}` : ''
      return `{ id: ${tsString(item.id)}, label: ${tsString(item.label)}${href}${permission}, order: ${item.order ?? 0}${children} }`
    })
    .join(', ')}]`
}

function renderReports(items) {
  return `[${(items ?? [])
    .map(
      (item) =>
        `{ id: ${tsString(item.id)}, label: ${tsString(item.label)}, href: ${tsString(item.href)}, permission: ${item.permission ? tsString(item.permission) : 'undefined'}, order: ${item.order ?? 0} }`,
    )
    .join(', ')}]`
}

function renderFile(manifest) {
  const permissions = (manifest.permissions ?? []).map(tsString).join(', ')
  const slots = (manifest.slots_provided ?? []).map(tsString).join(', ')
  const contributions = (manifest.slot_contributions ?? [])
    .map(
      (slot) =>
        `{ id: ${tsString(slot.contribution)}, slot: ${tsString(slot.name)}, order: ${slot.order ?? 0} }`,
    )
    .join(', ')
  return `/* Generated by scripts/codegen-plugin-ui.mjs — do not edit. */
import type { UiPlugin } from '../../platform/registry'

/** Metadata mirrored from the Rust PluginManifest for \`${manifest.id}\`. */
export const metadata = {
  id: ${tsString(manifest.id)},
  requiresBackend: true as const,
  permissions: [${permissions}] as string[],
  nav: ${renderNav(manifest.nav)} as UiPlugin['nav'],
  settingsPages: ${renderSettings(manifest.settings_pages)} as UiPlugin['settingsPages'],
  reportPages: ${renderReports(manifest.report_pages)} as UiPlugin['reportPages'],
  slotsProvided: [${slots}] as string[],
  contributions: [${contributions}] as Array<{ id: string; slot: string; order: number }>,
}
`
}

for (const manifest of manifests) {
  const dir = path.join(uiRoot, manifest.id)
  if (!fs.existsSync(dir)) continue
  const target = path.join(dir, 'manifest.generated.ts')
  const next = renderFile(manifest)
  const previous = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null
  if (previous === next) continue
  if (checkOnly) {
    stale += 1
    console.error(`stale: ${path.relative(root, target)}`)
    continue
  }
  fs.writeFileSync(target, next)
  wrote += 1
  console.log(`wrote ${path.relative(root, target)}`)
}

if (checkOnly && stale > 0) {
  console.error(`${stale} generated UI manifest(s) are out of date; run codegen.`)
  process.exit(1)
}
if (!checkOnly) {
  console.log(`UI manifests generated (${wrote} updated).`)
}
